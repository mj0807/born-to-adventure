-- Born to Adventure customer reviews
create table if not exists public.customer_reviews (
  id bigint generated by default as identity primary key,
  customer_name text not null check (char_length(customer_name) between 1 and 80),
  rating smallint not null check (rating between 1 and 5),
  review_text text not null check (char_length(review_text) between 1 and 2000),
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.customer_reviews enable row level security;
grant usage on schema public to anon, authenticated;
grant insert, select on public.customer_reviews to anon, authenticated;
grant usage, select on sequence public.customer_reviews_id_seq to anon, authenticated;

drop policy if exists "Anyone can submit a customer review" on public.customer_reviews;
create policy "Anyone can submit a customer review"
on public.customer_reviews for insert to anon, authenticated
with check (
  char_length(trim(customer_name)) between 1 and 80
  and char_length(trim(review_text)) between 1 and 2000
  and rating between 1 and 5
);

drop policy if exists "Anyone can read published customer reviews" on public.customer_reviews;
create policy "Anyone can read published customer reviews"
on public.customer_reviews for select to anon, authenticated
using (is_published = true);
